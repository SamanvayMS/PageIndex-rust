"""Generate the Python 3.11 / Unicode 14 tables for `pi-pycompat` (Spike D).

Run with the parity venv (Python 3.11, unicodedata 14.0.0, `regex` installed):

    parity/.venv/bin/python crates/pi-pycompat/gen/unicode_tables.py

Writes:
  crates/pi-pycompat/src/unicode_tables.rs        range-compressed lookup tables (generated code)
  crates/pi-pycompat/tests/fixtures/unicode.json  independent conformance fixture

The fixture stores every per-code-point property as a run-length list over all 0x110000 code
points (the test expands it and checks each code point through the public lookup functions), the
str.lower()/str.upper() mappings that differ from identity, and the four normalization forms for
every non-Hangul-syllable code point whose result differs from identity plus random sequences.
"""
import json
import random
import sys
import unicodedata
from pathlib import Path

import regex

assert sys.version_info[:2] == (3, 11), sys.version
assert unicodedata.unidata_version == "14.0.0", unicodedata.unidata_version

ROOT = Path(__file__).resolve().parent.parent
N = 0x110000

CATS = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi",
        "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]
BIDI = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO",
        "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI", ""]
NUMBER_RE = regex.compile(r"\p{Number}")


def runs(values):
    """[(start, value), ...] for maximal runs."""
    out = []
    prev = object()
    for cp, v in enumerate(values):
        if v != prev:
            out.append((cp, v))
            prev = v
    return out


def rle(values):
    """[[value, length], ...] over the whole code space (fixture form)."""
    out = []
    for v in values:
        if out and out[-1][0] == v:
            out[-1][1] += 1
        else:
            out.append([v, 1])
    return out


def rust_str(s):
    return '"' + "".join(c if (c.isprintable() and c not in '"\\' and ord(c) < 0x7f) else f"\\u{{{ord(c):x}}}"
                         for c in s) + '"'


def emit_ranges(lines, name, ty, rs, fmt):
    lines.append(f"pub(crate) static {name}: [(u32, {ty}); {len(rs)}] = [")
    row = []
    for cp, v in rs:
        row.append(f"(0x{cp:X}, {fmt(v)})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    lines.append("")


def main():
    chars = [chr(cp) for cp in range(N)]
    cat = [unicodedata.category(c) for c in chars]
    bidi = [unicodedata.bidirectional(c) for c in chars]
    assert set(cat) <= set(CATS), set(cat) - set(CATS)
    assert set(bidi) <= set(BIDI), set(bidi) - set(BIDI)
    number = [bool(NUMBER_RE.match(c)) for c in chars]
    # Surrogates cannot be `str.lower()`-ed meaningfully and never reach Rust `char`s.
    lower = {cp: c.lower() for cp, c in enumerate(chars) if not 0xD800 <= cp <= 0xDFFF and c.lower() != c}
    upper = {cp: c.upper() for cp, c in enumerate(chars) if not 0xD800 <= cp <= 0xDFFF and c.upper() != c}
    # Final_Sigma context classes, probed through str.lower() itself: 0 = stops the scan and is
    # not cased, 1 = case-ignorable (skipped), 2 = stops the scan and is cased.
    sigma = []
    for cp, c in enumerate(chars):
        if 0xD800 <= cp <= 0xDFFF:
            sigma.append(0)
        elif (c + "\u03a3").lower().endswith("\u03c2"):
            sigma.append(2)
        elif ("a" + c + "\u03a3").lower().endswith("\u03c2"):
            sigma.append(1)
        else:
            sigma.append(0)

    lines = [
        "// @generated by crates/pi-pycompat/gen/unicode_tables.py -- do not edit.",
        f"// Python {sys.version.split()[0]}, unicodedata {unicodedata.unidata_version}, regex {regex.__version__}.",
        "",
        "use crate::unicode::{Bidi, Cat};",
        "",
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// `unicodedata.category`: run starts (code point, category), sorted.",
    ]
    emit_ranges(lines, "CATEGORY", "Cat", runs(cat), lambda v: f"Cat::{v}")
    lines.append("/// `unicodedata.bidirectional`: run starts, sorted (`Bidi::None` = the empty string).")
    emit_ranges(lines, "BIDI", "Bidi", runs(bidi), lambda v: f"Bidi::{v or 'None'}")
    lines.append("/// `regex` module `\\p{Number}`: run starts, sorted.")
    emit_ranges(lines, "REGEX_NUMBER", "bool", runs(number), lambda v: "true" if v else "false")
    lines.append("/// Final_Sigma scan class (0 uncased stop, 1 case-ignorable, 2 cased stop): run starts.")
    emit_ranges(lines, "SIGMA_CLASS", "u8", runs(sigma), str)
    for name, table in (("LOWER", lower), ("UPPER", upper)):
        lines.append(f"/// `str.{name.lower()}()` for code points whose mapping is not the identity, sorted.")
        lines.append(f"pub(crate) static {name}: [(u32, &str); {len(table)}] = [")
        for cp, s in sorted(table.items()):
            lines.append(f"    (0x{cp:X}, {rust_str(s)}),")
        lines.append("];")
        lines.append("")
    out_rs = ROOT / "src" / "unicode_tables.rs"
    out_rs.write_text("\n".join(lines))

    rng = random.Random(14)
    norm = {}
    for form in ("NFC", "NFD", "NFKC", "NFKD"):
        norm[form] = [[cp, unicodedata.normalize(form, c)] for cp, c in enumerate(chars)
                      if not 0xD800 <= cp <= 0xDFFF and not 0xAC00 <= cp <= 0xD7A3
                      and unicodedata.normalize(form, c) != c]
    # Sequences mixing starters, combining marks (reordering + composition), Hangul jamo and
    # syllables, compatibility characters and code points unassigned in Unicode 14.
    pool = ("aeiouAEOnc" "̧̛̣̀́̂̈ͅ" "각가각"
            "ﬁ①Ａ½ΩÅཱི̈́"
            "\U0001e030\U00011f00ౝ୕\U00016fe4")  # 15.0+ additions: unassigned in 14.0
    seqs = []
    for _ in range(3000):
        s = "".join(rng.choice(pool) for _ in range(rng.randint(1, 8)))
        seqs.append([s] + [unicodedata.normalize(f, s) for f in ("NFC", "NFD", "NFKC", "NFKD")])
    hangul = []
    for cp in list(range(0xAC00, 0xD7A4, 97)) + [0xD7A3]:
        c = chr(cp)
        hangul.append([c] + [unicodedata.normalize(f, c) for f in ("NFC", "NFD", "NFKC", "NFKD")])
    fixture = {
        "python": sys.version.split()[0], "unicode": unicodedata.unidata_version,
        "category": rle(cat), "bidirectional": rle(bidi), "regex_number": rle([int(x) for x in number]),
        "sigma_class": rle(sigma),
        "lower": [[cp, s] for cp, s in sorted(lower.items())],
        "upper": [[cp, s] for cp, s in sorted(upper.items())],
        "normalize": norm, "normalize_seqs": seqs + hangul,
    }
    out_fx = ROOT / "tests" / "fixtures" / "unicode.json"
    out_fx.write_text(json.dumps(fixture, ensure_ascii=False, separators=(",", ":")))
    for p in (out_rs, out_fx):
        print(p, p.stat().st_size)


main()
